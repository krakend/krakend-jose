func HandlerFactory(hf ginlura.HandlerFactory, logger logging.Logger, rejecterF krakendjose.RejecterFactory) ginlura.HandlerFactory {
	return TokenSignatureValidator(TokenSigner(hf, logger), logger, rejecterF)
}

// TokenSigner gets the output generated by the next stage of the pipeline,
// and interprets it as JWT payload to be signed. If the signing of the payload
// fails, it returns a Bad Request response.
// If there is no config, the middleware does nothing.
func TokenSigner(hf ginlura.HandlerFactory, logger logging.Logger) ginlura.HandlerFactory {
	return func(cfg *config.EndpointConfig, prxy proxy.Proxy) gin.HandlerFunc {
		logPrefix := fmt.Sprintf("[ENDPOINT: %s %s][JWTSigner]", cfg.Method, cfg.Endpoint)
		signerCfg, signer, err := krakendjose.NewSigner(cfg, nil)
		if err == krakendjose.ErrNoSignerCfg {
			logger.Debug(logPrefix, "Signer disabled")
			return hf(cfg, prxy)
		}
		if err != nil {
			logger.Error(logPrefix, "Unable to create the signer:", err.Error())
			return erroredHandler
		}

		logger.Debug(logPrefix, "Signer enabled")

		return func(c *gin.Context) {
			proxyReq := ginlura.NewRequest(cfg.HeadersToPass)(c, cfg.QueryString)
			ctx, cancel := context.WithTimeout(c, cfg.Timeout)
			defer cancel()

			response, err := prxy(ctx, proxyReq)
			if err != nil {
				logger.Error(logPrefix, "Proxy response:", err.Error())
				c.AbortWithStatus(http.StatusBadRequest)
				return
			}

			if response == nil {
				logger.Error(logPrefix, "Empty proxy response")
				c.AbortWithStatus(http.StatusBadRequest)
				return
			}

			if err := krakendjose.SignFields(signerCfg.KeysToSign, signer, response); err != nil {
				logger.Error(logPrefix, "Signing fields:", err.Error())
				c.AbortWithStatus(http.StatusBadRequest)
				return
			}

			for k, v := range response.Metadata.Headers {
				c.Header(k, v[0])
			}
			c.JSON(response.Metadata.StatusCode, response.Data)
		}
	}
}

func TokenSignatureValidator(hf ginlura.HandlerFactory, logger logging.Logger, rejecterF krakendjose.RejecterFactory) ginlura.HandlerFactory { // skipcq: GO-R1005
	return func(cfg *config.EndpointConfig, prxy proxy.Proxy) gin.HandlerFunc {
		logPrefix := fmt.Sprintf("[ENDPOINT: %s %s][JWTValidator]", cfg.Method, cfg.Endpoint)
		handler := hf(cfg, prxy)
		scfg, err := krakendjose.GetSignatureConfig(cfg)
		if err == krakendjose.ErrNoValidatorCfg {
			logger.Info(logPrefix, "Validator disabled")
			return handler
		}
		if err != nil {
			logger.Warning(logPrefix, "Unable to parse the configuration:", err.Error())
			return erroredHandler
		}

		if rejecterF == nil {
			rejecterF = new(krakendjose.NopRejecterFactory)
		}
		rejecter := rejecterF.New(logger, cfg)

		jwtChecker, err := krakendjose.NewJWTChecks(scfg, logger, logPrefix, rejecter)
		if err != nil {
			logger.Warning(logPrefix, "Unable to create JWT validator:", err.Error())
			return erroredHandler
		}

		paramExtractor := extractRequiredJWTClaims(cfg)
		strTokenExtractor := josehttp.StrTokenFromHeaderOrCookieFn(scfg.AuthHeaderName, scfg.CookieKey)
		propagators, err := krakendjose.NewPropagators(scfg.PropagateClaimsToHeader)
		if err != nil && err != krakendjose.ErrNoHeadersToPropagate {
			// -------------------------------------------------------------------
			// TODO: Should we return an error if claims wont be propagated as expected?
			//
			// originally this is not an error, but we could change the behaviour and return
			// an error if claims wont be available for some further checks down the
			// pipeline ? could cause an endpoint to not be available
			// -------------------------------------------------------------------
			logger.Warning(logPrefix, fmt.Sprintf("error preparing header propagators: %s", err.Error()))
		}

		return func(c *gin.Context) {
			strToken, err := strTokenExtractor(c.Request)
			if err != nil {
				// this is an error that we cannot find the tokehn so unauthorized is fine
				if scfg.OperationDebug {
					logger.Error(logPrefix, "Unable to validate the token:", err.Error())
				}
				c.AbortWithStatus(http.StatusUnauthorized)
				return
			}

			claims, err := jwtChecker.Check(strToken)
			if err != nil {
				c.AbortWithStatus(josehttp.CheckErrorToStatusCode(err))
				return
			}
			josehttp.PropagateHeaders(c.Request, propagators, claims, scfg.PropagateClaimsPreserveArray)
			paramExtractor(c, claims)
			handler(c)
		}
	}
}

func erroredHandler(c *gin.Context) {
	c.AbortWithStatus(http.StatusUnauthorized)
}

var jwtParamsPattern = regexp.MustCompile(`{{\.JWT\.([^}]*)}}`)

func extractRequiredJWTClaims(cfg *config.EndpointConfig) func(*gin.Context, map[string]interface{}) {
	var required []string

	for _, backend := range cfg.Backend {
		for _, match := range jwtParamsPattern.FindAllStringSubmatch(backend.URLPattern, -1) {
			if len(match) < 2 {
				continue
			}
			required = append(required, match[1])
		}
	}
	if len(required) == 0 {
		return func(_ *gin.Context, _ map[string]interface{}) {}
	}

	return func(c *gin.Context, claims map[string]interface{}) {
		cl := krakendjose.Claims(claims)
		for _, param := range required {
			// TODO: check for nested claims
			v, ok := cl.Get(param)
			if !ok {
				continue
			}
			c.Params = append(c.Params, gin.Param{Key: "JWT." + param, Value: v})
		}
	}
}

